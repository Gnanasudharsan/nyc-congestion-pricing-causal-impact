"""Quarto post-render step: keep first paint from waiting on files it does not need.

Quarto writes both colour schemes (light and dark) of the Bootstrap and
syntax-highlighting stylesheets, plus a duplicate "extra" link, as rel="stylesheet".
At load time its own script then sets the inactive ones to rel="disabled-stylesheet".
By then the browser has already blocked rendering on all of them. Here we start the
alternate (dark) and the duplicate as disabled. Quarto's script still enables whichever
scheme the visitor's preference or the toggle asks for, so dark mode works as before.

It also:

- loads the tooltip stylesheet without blocking (hover popups are turned off);
- adds width and height attributes to every PNG <img>, read from the file header,
  so the browser reserves space and the layout does not shift when figures load
  (Lighthouse CLS), and lazy-loads every figure except the overview's hero image;
- marks Quarto's classic <head> scripts ``defer``. They then run in document order
  after parsing, before DOMContentLoaded. Quarto's own inline code that uses these
  libraries runs inside a DOMContentLoaded handler, and its colour-scheme code at
  the top of <body> uses none of them, so behaviour is unchanged. Rendering no
  longer waits for about 60 KB of script;
- replaces the Bootstrap Icons web font (a 15 KB render-blocking stylesheet and a
  180 KB font) with the two icons the site uses, inlined as SVG from
  ``report/icons/`` (generated by ``cordon.viz.icons``).

Standard library only, so CI needs no extra packages (ADR 0013).
"""

import os
import re
import struct
from pathlib import Path

OUTPUT = Path(os.environ.get("QUARTO_PROJECT_OUTPUT_DIR", "_site"))
# Inactive colour-scheme stylesheets (Bootstrap and syntax highlighting): the alternate
# (dark) theme and Quarto's duplicate "extra" link.
INACTIVE_SCHEME = re.compile(
    r'rel="stylesheet"((?: append-hash="true")? class="'
    r'(?:quarto-color-scheme quarto-color-alternate|quarto-color-scheme-extra)")'
)
# Tooltip styles: hover popups are turned off, so this need not block first paint.
TIPPY = '<link href="site_libs/quarto-html/tippy.css" rel="stylesheet">'
TIPPY_LATE = (
    '<link href="site_libs/quarto-html/tippy.css" rel="stylesheet" media="print" '
    "onload=\"this.media='all'\">"
)

IMG = re.compile(r'<img src="([^"]+\.png)"([^>]*)>')
HEAD_SCRIPT = re.compile(r'<script src="([^"]+)"></script>')
ICON = re.compile(r'<i class="bi bi-([a-z-]+)"([^>]*)>\s*</i>')
ICON_STYLESHEET = re.compile(r'<link href="[^"]*bootstrap-icons\.css" rel="stylesheet">\n?')
ICONS_DIR = Path(__file__).resolve().parent.parent / "icons"
SVG_BODY = re.compile(r"<svg[^>]*(viewBox=\"[^\"]+\")>(.*)</svg>", re.S)


def png_size(path: Path) -> tuple[int, int]:
    """Width and height from a PNG's IHDR chunk."""
    with path.open("rb") as handle:
        header = handle.read(24)
    width, height = struct.unpack(">II", header[16:24])
    return width, height


def add_dimensions(page: Path, html: str) -> str:
    """Give every PNG image intrinsic width/height attributes, and lazy-load non-hero ones."""

    def replace(match: re.Match[str]) -> str:
        source, rest = match.group(1), match.group(2)
        if "width=" in rest or "height=" in rest:
            return match.group(0)
        image = (page.parent / source).resolve()
        if not image.exists():
            return match.group(0)
        width, height = png_size(image)
        # Figures below the fold load lazily so they do not compete with the text that
        # paints first; the overview's hero figure is near the top and stays eager.
        lazy = "" if "hero-figure" in rest else ' loading="lazy" decoding="async"'
        return f'<img src="{source}" width="{width}" height="{height}"{lazy}{rest}>'

    return IMG.sub(replace, html)


def defer_head_scripts(html: str) -> str:
    """Add ``defer`` to classic external scripts in <head> (module scripts already defer)."""
    head, separator, body = html.partition("</head>")
    head = HEAD_SCRIPT.sub(r'<script src="\1" defer></script>', head)
    return head + separator + body


def inline_icons(html: str) -> str:
    """Swap icon-font <i> tags for inline SVG; drop the icon-font stylesheet if all were swapped."""

    def replace(match: re.Match[str]) -> str:
        name, attributes = match.group(1), match.group(2)
        source = ICONS_DIR / f"{name}.svg"
        if not source.exists():
            return match.group(0)
        svg = SVG_BODY.search(source.read_text(encoding="utf-8"))
        if svg is None:
            return match.group(0)
        if "aria-label" not in attributes:
            attributes += ' aria-hidden="true"'
        return (
            f'<svg class="bi bi-{name}" {svg.group(1)} width="1em" height="1em" '
            f'fill="currentColor"{attributes}>{svg.group(2)}</svg>'
        )

    html = ICON.sub(replace, html)
    if not ICON.search(html):
        html = ICON_STYLESHEET.sub("", html)
    return html


for page in OUTPUT.rglob("*.html"):
    html = page.read_text(encoding="utf-8")
    patched = INACTIVE_SCHEME.sub(r'rel="disabled-stylesheet"\1', html)
    patched = patched.replace(TIPPY, TIPPY_LATE)
    patched = add_dimensions(page, patched)
    patched = defer_head_scripts(patched)
    patched = inline_icons(patched)
    if patched != html:
        page.write_text(patched, encoding="utf-8")
