"""Generate docs/descriptives.md from the Phase 2 figure statistics and MDEs.

Every number on the page is read from generated files
(data/final/figures/pretrend_stats.csv, data/final/mde_pre_period.csv,
data/catalog/validation.json); none is typed by hand. Run after
``python -m cordon.viz.descriptive`` and ``python -m cordon.robustness.mde``.
"""

from __future__ import annotations

import json

import polars as pl

from cordon.config import DATA_DIR, REPO_ROOT
from cordon.robustness.mde import OUTPUT as MDE_CSV
from cordon.viz.descriptive import COMPARISONS, FIGURE_DATA_DIR

PAGE = REPO_ROOT / "docs" / "descriptives.md"
FIGURE_LINK = "../report/figures"

INTRO = """# Phase 2 descriptives (no effect estimates)

_Generated by `make descriptives` from files in `data/final/` and `data/catalog/`. Do not edit by
hand._

**What this page is.** Raw citywide trends before and after tolling, seasonality, and pre-trend
plots for every planned comparison. **What it is not.** It contains no treatment-effect
estimates.

- Comparison plots use **pre-period data only** (2023-01-01 to 2024-11-13).
- Before/after plots show **citywide aggregates only**, never treated against control
  (ADR 0002).

**How to read the pre-trend statistics.**
- Each group's series is centred on its units' own pre-period means.
- *Correlation* measures how closely the two groups' week-to-week (or month-to-month) movements
  track each other.
- *Gap trend* is the slope of the raw treated-minus-control gap per year.
- *Seasonally aligned gap* compares each 2024 week (or month) with the same week of 2023. The
  pre-registered designs include unit x week-of-year fixed effects, so this is the pre-trend that
  matters for identification: it should be flat around zero. The raw correlation can be low
  simply because treated and control areas have different seasonal shapes.
- The naive SE ignores serial correlation, so it is optimistic. Read it as a screen, not a test.
  The formal checks are the event-study pre-period coefficients and the HonestDiD-style bounds in
  Phases 3 and 5.
"""


def pretrend_table() -> str:
    """Markdown table of pre-trend statistics."""
    stats = pl.read_csv(FIGURE_DATA_DIR / "pretrend_stats.csv")
    labels = {c.key: c for c in COMPARISONS}
    lines = [
        "| Outcome | Treated vs comparison | Periods | Correlation "
        "| Gap trend per year (naive SE) | Seasonally aligned gap: mean (SD) |",
        "|---|---|---|---|---|---|",
    ]
    for row in stats.iter_rows(named=True):
        comparison = labels[row["key"]]
        scale = 100 if comparison.log_scale else 1
        unit = "log pts" if comparison.log_scale else comparison.unit_label.split(",")[0]
        lines.append(
            f"| {row['key']} | {comparison.treated_label} vs {comparison.control_label} | "
            f"{int(row['periods'])} | {row['correlation']:.2f} | "
            f"{row['gap_slope_per_year'] * scale:+.1f} {unit} "
            f"({row['gap_slope_se'] * scale:.1f}) | "
            f"{row['aligned_mean']:+.1f} ({row['aligned_sd']:.1f}) {unit} |"
        )
    return "\n".join(lines)


def mde_table() -> str:
    """Markdown table of pre-period MDEs."""
    if not MDE_CSV.exists():
        return "_MDEs not yet computed._"
    mde = pl.read_csv(MDE_CSV)
    lines = [
        "| Outcome | Method | Placebo dates | Mean placebo estimate "
        "| MDE (80% power, 5% two-sided) |",
        "|---|---|---|---|---|",
    ]
    for row in mde.iter_rows(named=True):
        lines.append(
            f"| {row['key']} | {row['method']} | {row['placebos']} | "
            f"{row['placebo_mean']:+.2f} {row['unit']} | "
            f"{row['mde_80pct_power']:.2f} {row['unit']} |"
        )
    return "\n".join(lines)


def validation_summary() -> str:
    """One line per data check."""
    results = json.loads((DATA_DIR / "catalog" / "validation.json").read_text())
    lines = []
    for name, failures in results.items():
        status = "pass" if not failures else "**fail**: " + "; ".join(failures)
        lines.append(f"- `{name}`: {status}")
    return "\n".join(lines)


def figures() -> str:
    """Embed every generated figure."""
    stats = pl.read_csv(FIGURE_DATA_DIR / "pretrend_stats.csv")
    present = set(stats["key"])
    blocks = ["## Citywide trends and seasonality", ""]
    for name in (
        "trend_bt_all_facilities",
        "trend_tlc_all_trips",
        "trend_subway_all_entries",
        "seasonality_bt",
    ):
        if (REPO_ROOT / "report" / "figures" / f"{name}.png").exists():
            blocks.append(f"![{name}]({FIGURE_LINK}/{name}.png)\n")
    blocks += ["## Pre-trend plots", ""]
    for comparison in COMPARISONS:
        if comparison.key in present:
            blocks.append(f"![{comparison.key}]({FIGURE_LINK}/{comparison.name}.png)\n")
            blocks.append(
                f"![{comparison.key} aligned]({FIGURE_LINK}/aligned_{comparison.name}.png)\n"
            )
    return "\n".join(blocks)


def main() -> None:
    """Write docs/descriptives.md."""
    page = "\n\n".join(
        [
            INTRO,
            "## Pre-trend screen\n\n" + pretrend_table(),
            "## Minimum detectable effects (pre-period placebo dates)\n\n"
            + mde_table()
            + "\n\nMethod and caveats: `src/cordon/robustness/mde.py`.",
            "## Data tests\n\n" + validation_summary(),
            figures(),
        ]
    )
    PAGE.write_text(page + "\n")


if __name__ == "__main__":
    main()
