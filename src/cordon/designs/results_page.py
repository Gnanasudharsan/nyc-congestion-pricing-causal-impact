def zone_section() -> str:
    """Zone-level effects summary and equity associations."""
    zones = pl.read_csv(RESULTS / "zone_spillover_effects.csv")
    lines = [
        "| Group | Zones | Median raw effect | Median shrunk effect "
        "| Shrunk 10th-90th percentile | Median placebo SD (log pts x 100) |",
        "|---|---|---|---|---|---|",
    ]
    for design, label in (("S1", "Border ring"), ("S3", "Upper Manhattan + Bronx")):
        part = zones.filter(pl.col("design") == design)
        shrunk = part["shrunk_percent"].to_numpy()
        lines.append(
            f"| {label} ({design}) | {part.height} | {fmt(part['raw_percent'].median())}% | "
            f"{fmt(part['shrunk_percent'].median())}% | "
            f"{fmt(float(np.percentile(shrunk, 10)))}% to {fmt(float(np.percentile(shrunk, 90)))}% "
            f"| {fmt(100 * float(np.median(part['placebo_sd'].to_numpy())), 2, False)} |"
        )
    first = zones.row(0, named=True)
    summary = (
        f"Empirical-Bayes mean {fmt(100 * float(first['eb_mean']), 2)} log points x 100; "
        f"between-zone SD (tau) {fmt(100 * float(first['eb_tau2']) ** 0.5, 2, False)}."
    )
    assoc = pl.read_csv(RESULTS / "equity_associations.csv", infer_schema_length=None)
    alines = [
        "| Model | Covariate | Weighted correlation | Slope per SD (pct points) [95% CI] "
        "| p | Zones |",
        "|---|---|---|---|---|---|",
    ]
    for row in assoc.iter_rows(named=True):
        low = float(row["slope_per_sd"]) - 1.96 * float(row["se"])
        high = float(row["slope_per_sd"]) + 1.96 * float(row["se"])
        alines.append(
            f"| {row['model']} | {row['label']} | {fmt(row['weighted_correlation'], 2)} | "
            f"{fmt(row['slope_per_sd'], 2)} [{fmt(low, 2)}, {fmt(high, 2)}] | "
            f"{fmt_p(row['p_value'])} | {row['n_zones']} |"
        )
    return (
        "\n".join(lines)
        + "\n\n"
        + summary
        + "\n\n**Associations with neighbourhood characteristics (exploratory, population-"
        "weighted; HC1 SEs that ignore the estimation error in the shrunk effects).**\n\n"
        + "\n".join(alines)
    )


