"""Generate docs/results-phase3.md from the files in results/.

Every number on the page is read from a generated file; none is typed by hand.
Run after ``cordon.designs.run``, ``cordon.designs.replication``,
``cordon.designs.bayesian_sc``, ``cordon.robustness.mde``, and
``cordon.viz.estimates``.
"""

from __future__ import annotations

from typing import Any

import polars as pl

from cordon.config import REPO_ROOT
from cordon.designs.run import DID_OUTCOMES, SYNTHETIC_OUTCOMES

RESULTS = REPO_ROOT / "results"
PAGE = REPO_ROOT / "docs" / "results-phase3.md"
FIGURES = "../report/figures"

INTRO = """# Phase 3 results: core causal estimates

_Generated by `make analysis` from files in `results/`. Do not edit by hand._

**How to read this page.**
- Effects on log outcomes are reported as percent changes, 100 x (exp(b) - 1). Effects on PM2.5
  are reported in µg/m³.
- The **headline** for each DiD outcome is the pooled pre-registered estimate for post year 1
  (2025-01-05 to 2025-12-31), relative to the 2023-01-01 to 2024-11-13 baseline. The
  anticipation window has its own term.
- The **detrended** column is the pre-registered secondary specification (amendment 1,
  [ADR 0011](adr/0011-detrended-secondary-specification.md)). It removes unit-specific linear
  trends fitted on the pre-period. For T2, R4, A1, A3, and R2, "robust" also requires the two
  specifications to agree (analysis plan §8, §11).
- Robust / fragile / not supported labels are assigned in Phase 5 after the falsification
  tests. **Nothing on this page is a final claim.**
- Deviations from the plan made during Phase 3 (6-11) are in [deviations.md](deviations.md).
  Every one was logged before the estimate it affects was computed.
"""


def fmt(value: Any, digits: int = 1, signed: bool = True) -> str:
    """Format a number, or an em dash for missing values."""
    if value is None:
        return "—"
    number = float(value)
    if number != number:  # nan
        return "—"
    return f"{number:+.{digits}f}" if signed else f"{number:.{digits}f}"


def fmt_p(value: Any) -> str:
    """Format a p-value."""
    if value is None or float(value) != float(value):
        return "—"
    number = float(value)
    return "< 0.001" if number < 0.001 else f"{number:.3f}"


def unit_suffix(row: dict[str, Any]) -> str:
    """'%' for percent outcomes, otherwise the unit."""
    return "%" if row["reported_unit"] == "percent" else f" {row['reported_unit']}"


def did_effect(row: dict[str, Any]) -> str:
    """Estimate with its 95% CI."""
    return (
        f"{fmt(row['reported'])}{unit_suffix(row)} "
        f"[{fmt(row['reported_ci_low'])}, {fmt(row['reported_ci_high'])}]"
    )


def lookup(estimates: pl.DataFrame, key: str, spec: str, term: str) -> dict[str, Any] | None:
    """One row of the estimates table, or None."""
    rows = estimates.filter(
        (pl.col("key") == key) & (pl.col("spec") == spec) & (pl.col("term") == term)
    )
    return rows.row(0, named=True) if rows.height else None


def pretrend_p(pretrends: pl.DataFrame, key: str, spec_contains: str) -> str:
    """Pre-trend test p-value for an outcome's event study."""
    rows = pretrends.filter((pl.col("key") == key) & pl.col("spec").str.contains(spec_contains))
    if not rows.height:
        return "—"
    return fmt_p(rows.row(0, named=True)["p_value"])


def did_table(estimates: pl.DataFrame, pretrends: pl.DataFrame, family: str) -> str:
    """DiD outcomes: headline, detrended, anticipation, extended, pre-trend test."""
    lines = [
        "| Outcome | Headline, 2025 [95% CI] | p (method) | Detrended [95% CI] "
        "| Anticipation [95% CI] | 2026+ [95% CI] | Pre-trend test p (primary / detrended) "
        "| Clusters |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for outcome in DID_OUTCOMES:
        if outcome.family != family:
            continue
        weather = "_weather" if outcome.weather else ""
        if outcome.weather_columns != DID_OUTCOMES[0].weather_columns and outcome.weather:
            weather = "_weather_pbl"
        primary = lookup(estimates, outcome.key, f"pooled_year1{weather}", "post_year1")
        if primary is None:
            continue
        detrended = lookup(estimates, outcome.key, f"pooled_year1_detrended{weather}", "post_year1")
        anticipation = lookup(estimates, outcome.key, f"pooled_year1{weather}", "anticipation")
        extended = lookup(estimates, outcome.key, f"pooled_extended{weather}", "post_extended")
        checks = []
        if primary.get("p_wild_bootstrap") is not None:
            checks.append(f"WCB p = {fmt_p(primary['p_wild_bootstrap'])}")
        if primary.get("p_cluster_t") is not None:
            checks.append(f"cluster-t p = {fmt_p(primary['p_cluster_t'])}")
        method = primary["p_method"] + ("; " + "; ".join(checks) if checks else "")
        pre_primary = pretrend_p(pretrends, outcome.key, f"event_study_year1{weather}$")
        pre_detrended = pretrend_p(pretrends, outcome.key, f"event_study_year1_detrended{weather}$")
        lines.append(
            f"| **{outcome.key}** {outcome.description} | {did_effect(primary)} | "
            f"{fmt_p(primary['p_value'])} ({method}) | "
            f"{did_effect(detrended) if detrended else '—'} | "
            f"{did_effect(anticipation) if anticipation else '—'} | "
            f"{did_effect(extended) if extended else '—'} | "
            f"{pre_primary} / {pre_detrended} | {primary['n_clusters']} {primary['cluster']} |"
        )
    return "\n".join(lines)


def synthetic_table(estimates: pl.DataFrame, family: str) -> str:
    """Synthetic-control outcomes."""
    lines = [
        "| Outcome | Year-1 gap | Placebo p (min possible) | Placebo effect range "
        "| Detrended gap (p) | Anticipation gap | 2026+ gap | Pre-RMSPE vs median placebo "
        "| Fit check | Donors |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for outcome in SYNTHETIC_OUTCOMES:
        if outcome.family != family:
            continue
        row = lookup(estimates, outcome.key, "synthetic", "post_year1")
        if row is None:
            continue
        detrended = lookup(estimates, outcome.key, "synthetic_detrended", "post_year1")
        anticipation = lookup(estimates, outcome.key, "synthetic", "anticipation")
        extended = lookup(estimates, outcome.key, "synthetic", "post_extended")
        scale = 100.0 if row["reported_unit"] == "percent" else 1.0
        suffix = unit_suffix(row)
        placebo = (
            f"{fmt(float(row['placebo_effect_low']) * scale)} to "
            f"{fmt(float(row['placebo_effect_high']) * scale)}"
        )
        imputed = float(row.get("donor_cells_imputed") or 0)
        donors = f"{row['n_donors']}" + (f" ({imputed:.1%} of cells imputed)" if imputed else "")
        lines.append(
            f"| **{outcome.key}** {outcome.description} | {fmt(row['reported'])}{suffix} | "
            f"{fmt_p(row['p_value'])} ({fmt_p(row['min_attainable_p'])}) | {placebo} | "
            f"{fmt(detrended['reported']) + suffix if detrended else '—'} "
            f"({fmt_p(detrended['p_value']) if detrended else '—'}) | "
            f"{fmt(anticipation['reported']) + suffix if anticipation else '—'} | "
            f"{fmt(extended['reported']) + suffix if extended else '—'} | "
            f"{fmt(float(row['pre_rmspe']) * scale, 2, False)} vs "
            f"{fmt(float(row['median_placebo_pre_rmspe']) * scale, 2, False)} | "
            f"{'pass' if row['fit_ok'] else '**fail: descriptive only**'} | {donors} |"
        )
    return "\n".join(lines)


def holm_section() -> str:
    """Primary-family Holm adjustment."""
    holm = pl.read_csv(RESULTS / "primary_holm.csv")
    lines = [
        "| Outcome | Estimate | Pre-registered p | Method | Smallest attainable p | Holm p "
        "| Reject at 5% (FWER) |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in holm.iter_rows(named=True):
        suffix = "%" if row["reported_unit"] == "percent" else f" {row['reported_unit']}"
        lines.append(
            f"| {row['key']} | {fmt(row['reported'])}{suffix} | {fmt_p(row['p_value'])} | "
            f"{row['p_method']} | {fmt_p(row['min_attainable_p'])} | {fmt_p(row['p_holm'])} | "
            f"{'yes' if row['reject_at_5pct'] else 'no'} |"
        )
    return "\n".join(lines)


def replication_section() -> str:
    """Pandey, Guler & Gayah (2026) replication."""
    table = pl.read_csv(RESULTS / "replication_pandey.csv")
    lines = [
        "| Control group | Week convention | β (SE) | Published β (SE) | Zones | Obs |",
        "|---|---|---|---|---|---|",
    ]
    for row in table.iter_rows(named=True):
        lines.append(
            f"| {row['control_group'].replace('_', ' ')} | {row['week_convention']} | "
            f"{fmt(row['beta'], 4)} ({fmt(row['se'], 4, False)}) | "
            f"{fmt(row['published_beta'], 4)} ({fmt(row['published_se'], 4, False)}) | "
            f"{row['n_zones']} | {row['n_obs']:,} |"
        )
    return "\n".join(lines)


def crosscheck_section() -> str:
    """pyfixest, CausalPy, and MDE comparisons."""
    lines = ["**pyfixest re-fit of the pooled primary specification (ADR 0005).**", ""]
    lines += ["| Outcome | Ours β (SE) | pyfixest β (SE) |", "|---|---|---|"]
    for row in pl.read_csv(RESULTS / "crosschecks.csv").iter_rows(named=True):
        lines.append(
            f"| {row['key']} | {fmt(row['ours'], 5)} ({fmt(row['ours_se'], 5, False)}) | "
            f"{fmt(row['reference'], 5)} ({fmt(row['reference_se'], 5, False)}) |"
        )
    bayes_path = RESULTS / "bayesian_sc_crosscheck.csv"
    if bayes_path.exists():
        lines += [
            "",
            "**CausalPy Bayesian synthetic control (ADR 0009).** Raw scale: log points or µg/m³. "
            "The credible interval covers only uncertainty in the synthetic mean, so it is "
            "narrower than a predictive interval.",
            "",
            "| Outcome | Frequentist gap | Posterior mean [95% credible interval] |",
            "|---|---|---|",
        ]
        for row in pl.read_csv(bayes_path).iter_rows(named=True):
            lines.append(
                f"| {row['key']} | {fmt(row['frequentist_effect'], 4)} | "
                f"{fmt(row['posterior_mean'], 4)} [{fmt(row['ci_low'], 4)}, "
                f"{fmt(row['ci_high'], 4)}] |"
            )
    mde_fitted = RESULTS / "mde_fitted_sc.csv"
    mde_proxy = REPO_ROOT / "data" / "final" / "mde_pre_period.csv"
    if mde_fitted.exists() and mde_proxy.exists():
        proxy = pl.read_csv(mde_proxy)
        lines += [
            "",
            "**Minimum detectable effects (80% power), deviation 2 follow-up.**",
            "",
            "| Outcome | Phase 2 equal-weight proxy | Phase 3 fitted synthetic control "
            "| Mean placebo estimate (fitted) |",
            "|---|---|---|---|",
        ]
        for row in pl.read_csv(mde_fitted).iter_rows(named=True):
            old = proxy.filter(pl.col("key") == row["key"]).row(0, named=True)
            lines.append(
                f"| {row['key']} | {fmt(old['mde_80pct_power'], 2, False)} {row['unit']} | "
                f"{fmt(row['mde_80pct_power'], 2, False)} {row['unit']} | "
                f"{fmt(row['placebo_mean'], 2)} {row['unit']} |"
            )
    return "\n".join(lines)


def figures() -> str:
    """Embed the Phase 3 figures."""
    blocks = ["## Figures", ""]
    for outcome in DID_OUTCOMES:
        if outcome.family != "check":
            name = f"phase3_event_study_{outcome.key.lower()}"
            if (REPO_ROOT / "report" / "figures" / f"{name}.png").exists():
                blocks.append(f"![{outcome.key}]({FIGURES}/{name}.png)\n")
    for synthetic in SYNTHETIC_OUTCOMES:
        name = f"phase3_synthetic_{synthetic.key.lower()}"
        if (REPO_ROOT / "report" / "figures" / f"{name}.png").exists():
            blocks.append(f"![{synthetic.key}]({FIGURES}/{name}.png)\n")
    return "\n".join(blocks)


def main() -> None:
    """Write docs/results-phase3.md."""
    estimates = pl.read_csv(RESULTS / "estimates.csv", infer_schema_length=None)
    pretrends = pl.read_csv(RESULTS / "pretrend_tests.csv")
    sections = [
        INTRO,
        "## Primary outcomes: Holm adjustment across the six (ADR 0008)\n\n" + holm_section(),
        "## Primary outcomes: difference-in-differences\n\n"
        + did_table(estimates, pretrends, "primary"),
        "## Primary outcomes: synthetic control\n\n" + synthetic_table(estimates, "primary"),
        "## Secondary outcomes (unadjusted p; BH q-values in Phase 5)\n\n"
        + did_table(estimates, pretrends, "secondary")
        + "\n\n"
        + synthetic_table(estimates, "secondary"),
        "## Checks\n\n" + did_table(estimates, pretrends, "check"),
        "## Replication: Pandey, Guler & Gayah (2026)\n\n" + replication_section(),
        "## Cross-checks and power\n\n" + crosscheck_section(),
        figures(),
    ]
    PAGE.write_text("\n\n".join(sections).rstrip() + "\n")


if __name__ == "__main__":
    main()
