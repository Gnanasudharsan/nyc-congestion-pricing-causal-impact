def dowhy_section() -> str:
    """DoWhy refuter results."""
    path = RESULTS / "dowhy_refuters.csv"
    if not path.exists():
        return "_Not run._"
    table = pl.read_csv(path, infer_schema_length=None)
    lines = ["| Outcome | Refuter | Original estimate | New effect | p |", "|---|---|---|---|---|"]
    for row in table.iter_rows(named=True):
        lines.append(
            f"| {row['key']} | {row['refuter']} | {fmt(row['estimate'], 4)} | "
            f"{fmt(row['new_effect'], 4)} | {fmt_p(row['p_value'])} |"
        )
    return (
        "On fixed-effect-residualised data (deviation 20). The placebo refuter permutes "
        "treatment across rows, ignoring panel structure; a new effect near zero is the "
        "expected result.\n\n" + "\n".join(lines)
    )


